function getTranslation(lang, path) {
  return path.split(".").reduce((obj, key) => obj?.[key], translations[lang]);
}

function applyLanguage(lang) {
  const selected = translations[lang] ? lang : "en";

  document.documentElement.lang = selected === "cs" ? "cs" : "en";

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const value = getTranslation(selected, el.dataset.i18n);
    if (typeof value === "string") el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const value = getTranslation(selected, el.dataset.i18nHtml);
    if (typeof value === "string") el.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const value = getTranslation(selected, el.dataset.i18nPlaceholder);
    if (typeof value === "string") el.placeholder = value;
  });

  const switcher = document.getElementById("langSwitch");
  if (switcher) {
    switcher.textContent = selected === "en" ? "EN / CS" : "CS / EN";
    switcher.setAttribute(
      "aria-label",
      selected === "en" ? "Switch to Czech" : "Switch to English"
    );
  }

  localStorage.setItem("egardee-language", selected);
  window.egardeeLanguage = selected;
}

document.addEventListener("DOMContentLoaded", () => {
  const saved = localStorage.getItem("egardee-language") || "en";
  applyLanguage(saved);

  document.getElementById("langSwitch")?.addEventListener("click", () => {
    applyLanguage(window.egardeeLanguage === "en" ? "cs" : "en");
  });
});
